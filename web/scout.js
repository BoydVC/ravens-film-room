/* Ravens Film Room · Scouting Report: renders data/scout.json (live via /api/scout, or inlined in the offline snapshot).
   ESPN public data only. Nothing estimated; missing fields are left out. */
(function () {
  "use strict";
  const $ = (s) => document.querySelector(s);
  const { esc, fmtET, tcol } = window.FR;
  let S, F, O, T;
  const col = (ab) => tcol(T, ab);
  const et = (iso, o) => fmtET(iso, o || { month: "short", day: "numeric", hour: "numeric", minute: "2-digit" }) + " ET";
  const sgn = (n) => (n > 0 ? "+" + n : n < 0 ? "−" + Math.abs(n) : "0");
  const ml = (n) => (n > 0 ? "+" + n : String(n));

  function render(data) {
    S = data; F = S.focus; O = S.opp; T = { teams: S.teams };
    document.documentElement.style.setProperty("--opp", col(O));
    $("#kick").textContent = `WEEK ${S.game.week ?? ""} · ${F} @ ${O}`.replace(`${F} @ ${O}`, `${S.game.away} @ ${S.game.home}`);
    matchup(); keys(); stats(); results(); oppDrives(); injuries(); audit(); sources();
    document.body.dataset.ready = "1";
  }

  function matchup() {
    const g = S.game, A = S.teams[g.away], H = S.teams[g.home];
    const side = (t, right) => `<div class="tm ${right ? "r" : ""}"><div><div class="ab" style="color:${col(t.abbr)}">${esc(t.abbr)}</div><div class="nm">${esc(t.name)}</div><div class="rec">${t.record ? esc(t.record) : ""} · ${t.homeAway === "home" ? "HOME" : "AWAY"}</div></div></div>`;
    const o = S.odds, p = S.predictor;
    const line = o ? `<div class="line"><div class="lk">BETTING LINE · ${esc(o.provider || "")}</div>
        <div class="lv">${esc(o.details || "")}${o.overUnder != null ? ` <span>·</span> O/U ${o.overUnder}` : ""}</div>
        <div class="ls2">${o.awayML != null ? `${esc(o.away)} ML ${ml(o.awayML)}` : ""}${o.homeML != null ? ` · ${esc(o.home)} ML ${ml(o.homeML)}` : ""}${o.overOdds != null ? ` · over ${ml(o.overOdds)} / under ${ml(o.underOdds)}` : ""}</div>
        <div class="src">Source: ${esc(o.source)}, fetched ${et(o.fetchedAt)}. Lines move; this is a snapshot.</div></div>` : `<div class="line"><div class="src">ESPN's public pre-game data has no betting line for this game, so none is shown.</div></div>`;
    const pred = p && p.homePct && p.awayPct ? `<div class="pred"><div class="lk">${esc(p.label || "ESPN Matchup Predictor")}</div>
        <div class="pbar"><i style="width:${p.awayPct}%;background:${col(p.away)}"></i><i style="width:${p.homePct}%;background:${col(p.home)}"></i></div>
        <div class="ls2"><b style="color:${col(p.away)}">${esc(p.away)} ${p.awayPct}%</b> · <b style="color:${col(p.home)}">${esc(p.home)} ${p.homePct}%</b> <span class="info">(ESPN's figures as published)</span></div></div>` : "";
    $("#matchup").innerHTML = side(A, false) + `<div class="mid"><div class="st">WEEK ${g.week ?? ""} · SCOUTING REPORT</div>
      <div class="at">${esc(g.away)} <span>@</span> ${esc(g.home)}</div>
      <div class="meta">${et(g.date, { weekday: "short", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" })}${g.venue ? " · " + esc(g.venue) : ""}${g.city ? ", " + esc(g.city) : ""}</div>
      ${line}${pred}</div>` + side(H, true);
  }

  const kfmt = (l, v) => (/margin/.test(l) ? sgn(v) : /rate/.test(l) ? v + "%" : v + " yds/g");
  function keys() {
    $("#keys").innerHTML = `<h2>Keys to the game<span class="aside">Generated by fixed rules from the biggest stat gaps below. Every number is from ESPN box scores (${S.season[F].games} games each).</span></h2>
      <div class="keys">${S.keys.map((k, i) => `<div class="key"><div class="kn">${i + 1}</div><div><div class="kt">${esc(k.title)}</div>
        <div class="kv">${k.nums.map(([l, v]) => `<span><em>${esc(l)}</em><b>${kfmt(l, v)}</b></span>`).join("")}</div>
        <div class="kx">${esc(k.text)}</div></div></div>`).join("")}</div>`;
  }

  function stats() {
    const a = S.season[F], b = S.season[O];
    const rows = [
      ["Offense", null],
      ["Points / game", "ppg", 1, (s) => `${s.pf} pts`],
      ["Total yards / game", "ypg", 1, (s) => `${s.yds} net yds`],
      ["Rushing yards / game", "rpg", 1, (s) => `${s.rush} yds`],
      ["Net passing yards / game", "ppgPass", 1, (s) => `${s.pass} yds`],
      ["3rd-down conversion %", "p3", 1, (s) => `${s.c3}/${s.a3}`],
      ["Red-zone TD %", "rz", 1, (s) => `${s.rzTD}/${s.rzAtt}`],
      ["Defense (allowed)", null],
      ["Points allowed / game", "papg", -1, (s) => `${s.pa} pts`],
      ["Total yards allowed / game", "ypgA", -1, (s) => `${s.ydsA} net yds`],
      ["Rushing yards allowed / game", "rpgA", -1, (s) => `${s.rushA} yds`],
      ["Net passing allowed / game", "ppgPassA", -1, (s) => `${s.passA} yds`],
      ["3rd-down % allowed", "p3A", -1, (s) => `${s.c3A}/${s.a3A}`],
      ["Red-zone TD % allowed", "rzA", -1, (s) => `${s.rzTDA}/${s.rzAttA}`],
      ["Ball & discipline", null],
      ["Turnover margin", "margin", 1, (s) => `${s.take} take / ${s.give} give`],
      ["Penalties (yds / game)", "penYdspg", -1, (s) => `${s.pen} for ${s.penYds}`],
    ];
    const pctKey = (k) => /^p3|^rz/.test(k);
    const fmt = (k, v) => (v == null ? "n/a" : k === "margin" ? sgn(v) : pctKey(k) ? v + "%" : v);
    const body = rows.map(([lab, k, dir, sub]) => {
      if (!k) return `<tr class="grp"><td colspan="3">${lab}</td></tr>`;
      const va = a[k], vb = b[k]; if (va == null && vb == null) return "";
      const better = va === vb ? 0 : (va > vb ? 1 : -1) * dir; // which side is better by the raw number
      return `<tr><td class="sv ${better > 0 ? "best" : ""}" style="--c:${col(F)}"><b>${fmt(k, va)}</b><small>${esc(sub(a))}</small></td><td class="sl">${lab}</td><td class="sv r ${better < 0 ? "best" : ""}" style="--c:${col(O)}"><b>${fmt(k, vb)}</b><small>${esc(sub(b))}</small></td></tr>`;
    }).join("");
    $("#stats").innerHTML = `<h2>Season stats, side by side<span class="aside">Summed from ESPN box scores · cross-checked below</span></h2>
      <table class="sst"><tr><th style="color:${col(F)}">${esc(S.teams[F].name)}<br><small>${a.games} games</small></th><th></th><th style="color:${col(O)}">${esc(S.teams[O].name)}<br><small>${b.games} games</small></th></tr>${body}</table>
      <div class="info" style="font-size:12px;margin-top:6px">Highlighted = the better number of the two (higher for offense and turnover margin, lower for defense and penalties). Yards are ESPN's box-score net yards.</div>`;
  }

  function results() {
    const tbl = (ab) => `<div><h4 style="color:${col(ab)}">${esc(S.teams[ab].name)}${S.teams[ab].record ? ` · ${esc(S.teams[ab].record)}` : ""}</h4><table class="rt">
      <tr><th>Wk</th><th>Opp</th><th>Result</th><th>Yds</th><th>Yds A</th><th>TO</th></tr>
      ${S.results[ab].filter((r) => r.completed || r.id === S.game.id).map((r) => {
        const opp = `${r.home ? "vs" : "@"} ${esc(r.opp)}`;
        if (!r.completed) return `<tr class="next"><td>${r.week ?? ""}</td><td>${opp}</td><td colspan="4">${et(r.date, { weekday: "short", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" })} · this game</td></tr>`;
        const res = `<span class="${r.result}">${r.result} ${r.us}-${r.them}</span>`;
        const link = ab === F ? `<a href="index.html?game=${r.id}" class="flink">${res}</a>` : res;
        return `<tr><td>${r.week ?? ""}</td><td>${opp}</td><td>${link}</td><td>${r.box ? r.box.yds : ""}</td><td>${r.box ? r.box.ydsA : ""}</td><td>${r.box ? r.box.give : ""}</td></tr>`;
      }).join("")}</table></div>`;
    $("#results").innerHTML = `<h2>Game by game<span class="aside">ESPN schedules + box scores · TO = giveaways</span></h2><div class="rts">${tbl(F)}${tbl(O)}</div>`;
  }

  function oppDrives() {
    const G = S.oppLastGame, A = G.teams[G.away], H = G.teams[G.home];
    const host = $("#oppdrives");
    host.innerHTML = `<div class="ohead"><div class="ok2">${esc(O)}'S LAST GAME · WEEK ${G.week ?? ""}</div><div class="osc"><b style="color:${tcol(G, G.away)}">${esc(G.away)} ${A.score}</b> @ <b style="color:${tcol(G, G.home)}">${esc(G.home)} ${H.score}</b> <span class="info">${et(G.date, { weekday: "short", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" })}${G.venue ? " · " + esc(G.venue) : ""}</span></div></div><div id="odc"></div>`;
    FR.driveChart($("#odc"), G, { title: `${esc(S.teams[O].short || O)} drive chart`, aside: `Same renderer as the Film Room. ${esc(O)} always attacks ▶. Click a drive for its play-by-play (ESPN text, verbatim).` });
  }

  function injuries() {
    const has = Object.values(S.injuries || {}).some((v) => v.length);
    if (!has) { $("#injuries").innerHTML = `<h2>Injury report</h2><div class="info">ESPN's public pre-game data has no injury report for this game, so none is shown.</div>`; return; }
    const tbl = (ab) => `<div><h4 style="color:${col(ab)}">${esc(S.teams[ab].name)}</h4>${(S.injuries[ab] || []).length ? (S.injuries[ab] || []).map((i) => `<div class="inj"><div><b>${esc(i.name)}</b> <span class="info">${esc(i.pos || "")}</span>${i.injury ? `<div class="info">${esc(i.injury)}</div>` : ""}</div><div class="ist ${/out|reserve/i.test(i.status || "") ? "out" : "q"}">${esc(i.status || "")}</div></div>`).join("") : `<div class="info">None listed.</div>`}</div>`;
    $("#injuries").innerHTML = `<h2>Injury report<span class="aside">ESPN pre-game summary, fetched ${et(S.sources.pregame.fetchedAt)}</span></h2><div class="ld">${tbl(F)}${tbl(O)}</div>`;
  }

  function audit() {
    const rows = S.checks;
    const ok = rows.filter((c) => c.ok).length;
    const tbl = (ab) => `<table class="aud2"><tr><th style="color:${col(ab)}">${esc(ab)}</th><th>Box-score sum</th><th>ESPN</th><th></th></tr>${rows.filter((c) => c.team === ab).map((c) => `<tr><td>${esc(c.label)} <span class="info">· ${esc(c.source)}</span></td><td>${c.ours}</td><td>${c.espn ?? "n/a"}</td><td>${c.ok ? '<span class="ok">✓ match</span>' : '<span style="color:var(--to)">✕ mismatch</span>'}</td></tr>`).join("")}</table>`;
    $("#saudit").innerHTML = `<h2>Stat audit: our box-score sums vs. ESPN's own season numbers<span class="aside">${ok}/${rows.length} match · same checks as tests/smoke_test.py</span></h2>
      <div class="au">${tbl(F)}${tbl(O)}</div>
      <div class="info" style="font-size:12px;margin-top:8px">"Season stats" = ESPN team statistics (sports.core.api). "Pre-game summary" = the per-game averages in ESPN's pre-game summary; its pass-yards-allowed figure is gross (opponents' net passing plus yards lost to sacks), so the sum here adds those sack yards back.</div>`;
  }

  function sources() {
    const s = S.sources;
    const ts = Object.entries(s.teamStats).map(([ab, x]) => `${esc(ab)} <code>${esc(x.url)}</code> (${et(x.fetchedAt)})`).join("; ");
    $("#ssources").innerHTML = `<b>Sources:</b> ESPN public JSON. Pre-game summary (injuries, line, predictor, per-game averages) <code>${esc(s.pregame.url)}</code>, fetched ${et(s.pregame.fetchedAt)}.
      Schedules <code>${esc(s.schedule.url)}</code> (${et(s.schedule.fetchedAt)}) and <code>${esc(s.oppSchedule.url)}</code> (${et(s.oppSchedule.fetchedAt)}).
      Season team statistics: ${ts}. Per-game box scores: ${Object.keys(s.summaries).length} ESPN game summaries (listed in data/raw/manifest.json).
      ESPN game page: <a href="${esc(S.game.espnPage)}">${esc(S.game.espnPage)}</a>. Nothing is estimated or filled in; missing fields are left out. Built ${et(S.generatedAt)} by TokenMax. Not affiliated with the NFL, ESPN, DraftKings or either team.`;
  }

  function fail(m) { document.getElementById("app").insertAdjacentHTML("afterbegin", `<div class="card" style="border-color:var(--to)"><b>Scouting data unavailable.</b> ${esc(m)}</div>`); document.body.dataset.ready = "error"; }
  if (window.__SCOUT__) { try { render(window.__SCOUT__); } catch (e) { fail(e.message); console.error(e); } }
  else fetch("/api/scout").then((r) => (r.ok ? r.json() : Promise.reject(new Error("HTTP " + r.status)))).then((d) => { try { render(d); } catch (e) { fail(e.message); console.error(e); } }).catch((e) => fail(e.message));
})();
